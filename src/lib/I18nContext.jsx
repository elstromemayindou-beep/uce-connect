const LanguageContext = createContext(null);
const supportedLanguages = new Set(['fr', 'ln', 'kg']);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = window.localStorage.getItem('uce-language');
    return supportedLanguages.has(savedLanguage) ? savedLanguage : 'fr';
  });

  useEffect(() => {
    window.localStorage.setItem('uce-language', language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (frenchText) => translations[language]?.[frenchText] || frenchText,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider.');
  return context;
}
